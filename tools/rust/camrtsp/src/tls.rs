//! TLS 1.2 for the ingest uploader, over mbedTLS.
//!
//! Why this exists and why it is C underneath: the ingest endpoint is public
//! (Cloudflare terminates every `*.ackl.me` hostname, so there is no plain-HTTP
//! path to the house). The camera therefore has to speak real TLS. Its own
//! `libssl.so.1.0.0` is uClibc and our binary is armv5te-musl, so that library
//! is not linkable; doing it in pure Rust would mean hand-writing X.509 plus
//! RSA/ECDSA verification. `tools/tls/` builds mbedTLS 2.28.8 for
//! arm-linux-musleabi and puts a six-function shim (`camtls.c`) in front of it,
//! so no mbedTLS struct layout is ever visible from here.
//!
//! What is verified: the peer chain against the roots embedded below, and the
//! hostname (SNI + CN/SAN). A failure is an error, never a warning — an
//! unverified upload is worse than no upload.
//!
//! Only TLS 1.2 is compiled in. That is deliberate: TLS 1.3 client support
//! arrived in mbedTLS 3.x, which does not build for this target as cleanly, and
//! Cloudflare still accepts 1.2 for these zones.

use std::ffi::c_void;
use std::io::{self, Read, Write};
use std::net::TcpStream;
use std::os::unix::io::AsRawFd;

/// Public roots only — generated by `tools/tls/build.sh bundle`, copied next to
/// this crate because `tools/remote-build.sh` syncs the crate directory and
/// nothing outside it.
const CA_BUNDLE: &[u8] = include_bytes!("../ca-bundle.pem");

/// `CAMTLS_CA=/path/to/roots.pem` replaces the embedded bundle. Two uses: testing
/// against a private CA (a LAN Caddy with `tls internal`), and the field case
/// where an endpoint moves to a CA we did not ship. Read once per handshake;
/// a file that cannot be read is an error, never a silent fall back to the
/// embedded roots.
fn ca_bundle() -> io::Result<std::borrow::Cow<'static, [u8]>> {
    use std::borrow::Cow;
    match std::env::var_os("CAMTLS_CA") {
        None => Ok(Cow::Borrowed(CA_BUNDLE)),
        Some(p) => {
            let bytes = std::fs::read(&p).map_err(|e| {
                io::Error::new(
                    io::ErrorKind::NotFound,
                    format!("CAMTLS_CA {}: {}", std::path::Path::new(&p).display(), e),
                )
            })?;
            if bytes.is_empty() {
                return Err(io::Error::new(
                    io::ErrorKind::InvalidData,
                    format!("CAMTLS_CA {} is empty", std::path::Path::new(&p).display()),
                ));
            }
            Ok(Cow::Owned(bytes))
        }
    }
}

const E_EOF: i32 = -1;
const E_WANT: i32 = -2;
const E_IO: i32 = -3;
const E_CLOSED: i32 = -4;

extern "C" {
    fn camtls_open(
        fd: i32,
        hostname: *const u8,
        ca_pem: *const u8,
        ca_len: usize,
        err: *mut u8,
        err_len: usize,
    ) -> *mut c_void;
    fn camtls_read(h: *mut c_void, buf: *mut u8, len: usize) -> i32;
    fn camtls_write(h: *mut c_void, buf: *const u8, len: usize) -> i32;
    fn camtls_version(h: *mut c_void) -> *const u8;
    fn camtls_ciphersuite(h: *mut c_void) -> *const u8;
    fn camtls_close(h: *mut c_void);
}

/// A TLS session on top of an already-connected socket. The socket is kept
/// alive here: mbedTLS reads and writes through its descriptor.
pub struct TlsStream {
    h: *mut c_void,
    // Declared after `h`: fields drop in declaration order, so the session is
    // torn down (which writes close_notify) before the descriptor closes. Never
    // read — mbedTLS works through the raw fd — only held alive.
    _sock: TcpStream,
}

impl TlsStream {
    /// Handshake, verifying the certificate against `host` and the embedded
    /// roots. The socket's own timeouts apply: a stalled peer surfaces as
    /// `TimedOut`, which upload.rs treats as a network failure and retries.
    pub fn connect(host: &str, sock: TcpStream) -> io::Result<TlsStream> {
        let fd = sock.as_raw_fd();
        let mut errbuf = [0u8; 256];
        // CString, not as_ptr(): a Rust &str has no terminator, and mbedTLS
        // strlen()s the hostname. Skipping this sent SNI "basestar.ackl.mebin"
        // (the bytes after the string in memory) and Cloudflare answered
        // handshake_failure because no zone owns that name.
        let c_host = std::ffi::CString::new(host).map_err(|_| {
            io::Error::new(io::ErrorKind::InvalidInput, "hostname contains a NUL byte")
        })?;
        let ca = ca_bundle()?;
        let h = unsafe {
            camtls_open(
                fd,
                c_host.as_ptr() as *const u8,
                ca.as_ptr(),
                ca.len(),
                errbuf.as_mut_ptr(),
                errbuf.len(),
            )
        };
        if h.is_null() {
            let n = errbuf.iter().position(|&b| b == 0).unwrap_or(errbuf.len());
            let msg = String::from_utf8_lossy(&errbuf[..n]).into_owned();
            return Err(io::Error::new(
                io::ErrorKind::Other,
                if msg.is_empty() {
                    format!("tls handshake with {host} failed")
                } else {
                    msg
                },
            ));
        }
        Ok(TlsStream { h, _sock: sock })
    }

    /// "TLSv1.2", "ECDHE-RSA-AES128-GCM-SHA256". For the log line and for
    /// `camrtsp tlsprobe`.
    pub fn session(&self) -> (String, String) {
        unsafe {
            let v = camtls_version(self.h);
            let c = camtls_ciphersuite(self.h);
            let mut out = (String::new(), String::new());
            if !v.is_null() {
                let mut n = 0;
                while *v.add(n) != 0 && n < 64 {
                    n += 1;
                }
                out.0 = String::from_utf8_lossy(std::slice::from_raw_parts(v, n)).into_owned();
            }
            if !c.is_null() {
                let mut n = 0;
                while *c.add(n) != 0 && n < 128 {
                    n += 1;
                }
                out.1 = String::from_utf8_lossy(std::slice::from_raw_parts(c, n)).into_owned();
            }
            out
        }
    }
}

impl Read for TlsStream {
    fn read(&mut self, buf: &mut [u8]) -> io::Result<usize> {
        if buf.is_empty() {
            return Ok(0);
        }
        loop {
            let n = unsafe { camtls_read(self.h, buf.as_mut_ptr(), buf.len()) };
            return match n {
                n if n >= 0 => Ok(n as usize),
                E_EOF => Ok(0),
                E_WANT => Err(io::Error::new(
                    io::ErrorKind::TimedOut,
                    "tls read timed out",
                )),
                E_CLOSED => Err(io::Error::new(
                    io::ErrorKind::BrokenPipe,
                    "tls stream already closed",
                )),
                E_IO => Err(io::Error::new(
                    io::ErrorKind::Other,
                    "tls read failed (bad record or peer gone)",
                )),
                _ => Err(io::Error::new(io::ErrorKind::Other, "tls read failed")),
            };
        }
    }
}

impl Write for TlsStream {
    /// Writes everything: mbedTLS emits exactly one record per call when it can,
    /// and the shim loops until the whole buffer is accepted.
    fn write(&mut self, buf: &[u8]) -> io::Result<usize> {
        if buf.is_empty() {
            return Ok(0);
        }
        let n = unsafe { camtls_write(self.h, buf.as_ptr(), buf.len()) };
        match n {
            n if n >= 0 => Ok(n as usize),
            E_WANT => Err(io::Error::new(
                io::ErrorKind::TimedOut,
                "tls write timed out",
            )),
            E_CLOSED => Err(io::Error::new(
                io::ErrorKind::BrokenPipe,
                "tls stream already closed",
            )),
            _ => Err(io::Error::new(io::ErrorKind::Other, "tls write failed")),
        }
    }

    fn flush(&mut self) -> io::Result<()> {
        // mbedTLS buffers a partial record at most; nothing to push by hand and
        // camtls_write returns only once the record has gone out.
        Ok(())
    }
}

impl Drop for TlsStream {
    fn drop(&mut self) {
        unsafe { camtls_close(self.h) };
        self.h = std::ptr::null_mut();
    }
}

/// Diagnostic used by `camrtsp tlsprobe HOST[:PORT]`: connect, verify, report
/// what came back. Runs on the camera too, which is the point — when an upload
/// fails in the field, this is what tells you whether it is TLS, DNS or the
/// receiver.
pub fn probe(target: &str, timeout: std::time::Duration) -> io::Result<String> {
    use std::net::ToSocketAddrs;
    let (host, port) = match target.rfind(':') {
        Some(i) if target[i + 1..].chars().all(|c| c.is_ascii_digit()) => {
            let p: u16 = target[i + 1..]
                .parse()
                .map_err(|_| io::Error::new(io::ErrorKind::InvalidInput, "bad port"))?;
            (&target[..i], p)
        }
        _ => (target, 443),
    };
    if host.is_empty() {
        return Err(io::Error::new(io::ErrorKind::InvalidInput, "no host"));
    }
    let addrs: Vec<_> = (host, port).to_socket_addrs()?.collect();
    if addrs.is_empty() {
        return Err(io::Error::new(
            io::ErrorKind::NotFound,
            format!("{host} did not resolve to any address"),
        ));
    }
    let mut last = None;
    let mut sock = None;
    for a in &addrs {
        match TcpStream::connect_timeout(a, timeout) {
            Ok(s) => {
                sock = Some(s);
                break;
            }
            Err(e) => last = Some(e),
        }
    }
    let sock = sock.ok_or_else(|| {
        last.unwrap_or_else(|| io::Error::new(io::ErrorKind::NotFound, "connect failed"))
    })?;
    let _ = sock.set_read_timeout(Some(timeout));
    let _ = sock.set_write_timeout(Some(timeout));
    let tls = TlsStream::connect(host, sock)?;
    let (v, c) = tls.session();
    let trust = match std::env::var_os("CAMTLS_CA") {
        Some(p) => format!("trust anchors from CAMTLS_CA {}", std::path::Path::new(&p).display()),
        None => format!("{} roots embedded, {} bytes", count_roots(), CA_BUNDLE.len()),
    };
    Ok(format!("{host}:{port} verified via {v} {c} ({trust})"))
}

fn count_roots() -> usize {
    let needle = b"BEGIN CERTIFICATE";
    CA_BUNDLE
        .windows(needle.len())
        .filter(|w| *w == needle)
        .count()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ca_bundle_has_the_roots_we_expect() {
        // If the bundle ever comes out empty or truncated, every upload fails in
        // the field with an unhelpful mbedTLS error. Catch it at test time.
        assert!(
            CA_BUNDLE.len() > 3000,
            "ca-bundle.pem is {} bytes",
            CA_BUNDLE.len()
        );
        assert!(count_roots() >= 4, "only {} roots", count_roots());
        // Cloudflare signs ackl.me from GTS Root R4 today (verified with
        // openssl s_client, see analysis/offsite-ingest.md). If the bundle stops
        // carrying that anchor, uploads fail with "verify failed" and nothing
        // else points at the bundle.
        let text = core::str::from_utf8(CA_BUNDLE).expect("bundle is text");
        assert!(text.contains("GTS Root R4"), "bundle lost the Cloudflare anchor");
        assert!(text.contains("ISRG Root X1"), "bundle lost the Let's Encrypt anchor");
    }

    #[test]
    fn probe_rejects_junk_without_panicking() {
        assert!(probe("", std::time::Duration::from_millis(50)).is_err());
        assert!(probe(":", std::time::Duration::from_millis(50)).is_err());
        // Port 1 on loopback: refused, not a panic.
        let r = probe("127.0.0.1:1", std::time::Duration::from_millis(200));
        assert!(r.is_err(), "connected to port 1?");
    }

    /// Live check against a real endpoint. Ignored by default because it needs
    /// the internet; run it when the chain or the CA bundle changes:
    ///   rustc --test ... && ./tls-tests --ignored
    #[test]
    #[ignore]
    fn handshake_to_a_real_host_verifies() {
        let out = probe("basestar.ackl.me", std::time::Duration::from_secs(10))
            .expect("handshake should verify");
        assert!(out.contains("TLSv1.2"), "{out}");
    }
}
